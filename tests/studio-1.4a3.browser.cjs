// EPP_BROWSER=/path/to/chromium npm run test:studio:alpha
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { chromium } = require('playwright-core');
const { GalleryStore, createServer } = require('../server.js');
(async () => {
  const exe = [process.env.EPP_BROWSER, process.env.CHROME_BIN, '/usr/bin/chromium'].find(p => p && fs.existsSync(p));
  if (!exe) throw new Error('Set EPP_BROWSER to a Chromium executable.');
  const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'epp-14a3-'));
  let server, browser;
  try {
    server = createServer(await new GalleryStore(path.join(temp, 'gallery.json')).init());
    await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
    browser = await chromium.launch({ executablePath: exe, args: ['--no-sandbox'] });
    const page = await browser.newPage({ viewport: { width: 1200, height: 800 } });
    const errors = []; page.on('pageerror', e => errors.push(String(e)));
    await page.goto(`http://127.0.0.1:${server.address().port}`);
    assert.equal(await page.locator('[data-action="btnGallery"]').count(), 0);
    assert.equal(await page.locator('#btnGallery').count(), 1);
    await page.locator('[data-activity="files"]').click();
    await page.locator('#fileSearch').fill('definitely-no-match-7e8b');
    assert.equal(await page.locator('.file-list-empty').innerText(), 'No files match your search.');
    await page.locator('#fileSearch').fill('');
    await page.evaluate(() => { files['z-test-10.enpp'] = ''; files['z-test-2.enpp'] = ''; renderFileList(); });
    await page.locator('#fileSearch').fill('z-test');
    assert.deepEqual(await page.locator('#fileList .file-name').allTextContents(), ['z-test-2.enpp', 'z-test-10.enpp']);
    await page.locator('#fileSearch').fill('');
    await page.evaluate(() => showToast('first'));
    await page.waitForTimeout(1200);
    await page.evaluate(() => showToast('second'));
    await page.waitForTimeout(1500);
    assert.equal(await page.locator('#toast').isVisible(), true);
    assert.equal(await page.locator('#toast').innerText(), 'second');
    await page.locator('[data-component="settings"]').click();
    assert.equal(await page.locator('#studioAnimations').isChecked(), true);
    assert.notEqual(await page.locator('#settingsDialog').evaluate(el => getComputedStyle(el).animationName), 'none');
    await page.locator('#studioAnimations').uncheck();
    assert.equal(await page.locator('#settingsDialog').evaluate(el => getComputedStyle(el).animationName), 'none');
    assert.equal(await page.evaluate(() => document.documentElement.classList.contains('studio-motion-off')), true);
    assert.equal(await page.locator('#autoRename').isChecked(), true);
    assert.equal(await page.locator('.theme-swatch').count(), 12);
    await page.getByRole('button', { name: 'Mint', exact: true }).focus();
    await page.keyboard.press('Enter');
    assert.equal(await page.evaluate(() => document.activeElement.getAttribute('aria-label')), 'Mint');
    await page.locator('#editorFontSize').selectOption('18');
    await page.locator('#showLineNumbers').uncheck();
    await page.locator('#settingsWrap').check();
    await page.locator('#autoRename').uncheck();
    await page.locator('#openStudioEditor').click();
    assert.equal(await page.locator('.layout-tile').count(), 10);
    await page.locator('.layout-tile[data-id="explorer"]').dragTo(page.locator('#zoneTop'), { sourcePosition: { x: 10, y: 18 } });
    assert.equal(await page.locator('#zoneTop .layout-tile[data-id="explorer"]').count(), 1);
    await page.locator('.layout-tile[data-id="run"] select').selectOption('hidden');
    assert.equal(await page.evaluate(() => document.activeElement.getAttribute('aria-label')), 'Move Run to');
    await page.locator('.layout-tile[data-id="settings"] select').selectOption('hidden');
    await page.locator('#layoutDone').click();
    assert.equal(await page.locator('#btnRun').isVisible(), false);
    assert.equal(await page.locator('#editorCard').isVisible(), true);
    assert.equal(await page.locator('#consoleCard').isVisible(), true);
    assert.equal(await page.locator('#btnTools').isVisible(), true);
    assert.equal(await page.locator('#launcherTop [data-component="explorer"]').isVisible(), true);
    await page.reload();
    assert.equal(await page.locator('#btnRun').isVisible(), false);
    assert.equal(await page.locator('#launcherTop [data-component="explorer"]').isVisible(), true);
    assert.equal(await page.locator('#lineNumbers').isVisible(), false);
    assert.equal(await page.locator('#editor').evaluate(el => getComputedStyle(el).fontSize), '18px');
    await page.locator('#btnTools').click(); await page.locator('#toolsFeatureList [data-hub-id="settings"]').click();
    assert.equal(await page.locator('#accentColor').inputValue(), '#83dcb7');
    assert.equal(await page.locator('#studioAnimations').isChecked(), false);
    await page.locator('#studioAnimations').check();
    await page.emulateMedia({ reducedMotion: 'reduce' });
    assert.equal(await page.locator('#settingsDialog').evaluate(el => getComputedStyle(el).animationName), 'none');
    await page.emulateMedia({ reducedMotion: 'no-preference' });
    assert.notEqual(await page.locator('#settingsDialog').evaluate(el => getComputedStyle(el).animationName), 'none');
    assert.equal(await page.locator('#autoRename').isChecked(), false);
    assert.equal(await page.locator('#settingsWrap').isChecked(), true);
    await page.locator('#resetAppearance').click();
    assert.equal(await page.locator('#accentColor').inputValue(), '#b7a4ff');
    assert.equal(await page.locator('#editorFontSize').inputValue(), '14');
    assert.equal(await page.locator('#showLineNumbers').isChecked(), true);
    assert.equal(await page.locator('#settingsWrap').isChecked(), false);
    assert.equal(await page.locator('#autoRename').isChecked(), false);
    await page.locator('#openStudioEditor').click();
    assert.equal(await page.locator('#zoneTop .layout-tile[data-id="explorer"]').count(), 1);
    await page.locator('[data-preset="default"]').click();
    await page.locator('#layoutDone').click();
    assert.equal(await page.locator('#btnRun').isVisible(), true);
    await page.locator('#btnTools').click();
    await page.locator('#toolsFeatureList [data-hub-id="news"]').click();
    await page.waitForURL('**/news.html');
    assert.match(await page.title(), /1\.4a3/);
    assert.equal(await page.locator('img').count(), 6);
    assert.equal(await page.locator('img').evaluateAll(imgs => imgs.every(i => i.complete && i.naturalWidth > 0)), true);
    assert.equal((await page.locator('.news-footer').innerText()).includes('Updated Daily'), true);
    await page.setViewportSize({ width: 390, height: 844 });
    await page.goto(`http://127.0.0.1:${server.address().port}`);
    assert.equal(await page.locator('#editorCard').isVisible(), true);
    assert.equal(await page.locator('#consoleCard').isVisible(), true);
    assert.equal(await page.locator('.bottom-bar').isVisible(), true);
    assert.deepEqual(errors, []);
    console.log('1.4rc1 motion, settings, accessibility, explorer, News and small-screen checks passed.');
  } finally { if (browser) await browser.close(); if (server) await new Promise(resolve => server.close(resolve)); fs.rmSync(temp, { recursive: true, force: true }); }
})().catch(e => { console.error(e); process.exitCode = 1; });
