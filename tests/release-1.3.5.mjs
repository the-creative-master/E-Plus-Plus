import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { DrawHost } = require('../js/draw-library.js');
const diagnostics = require('../js/diagnostics.js');
const sleep = ms => new Promise(resolve => setTimeout(resolve, ms));
const ctx = new Proxy({}, { get: (o, key) => o[key] || (() => {}), set: (o, key, value) => (o[key] = value, true) });
const host = new DrawHost({ width: 400, height: 300, getContext: () => ctx });
const sprite = host.create('pencil');
assert.equal(sprite.speed, 240);
host.setSpeed('pencil', 120);
let frames = 0;
const started = Date.now();
const moving = host.animateMove('pencil', 'right', 36, { onFrame: () => frames++ });
await sleep(90);
assert(sprite.x > 0 && sprite.x < 36, 'animation exposes an intermediate position');
host.move('pencil', 'down', 7); // Manual controls remain usable during animation.
await moving;
assert(Date.now() - started >= 240 && Date.now() - started < 2000, 'speed determines duration');
assert.equal(sprite.x, 36);
assert.equal(sprite.y, 7);
assert(frames >= 3, 'intermediate frames were rendered');
assert(host.strokes.length <= 3, 'animation does not create a stroke per frame');

host.setSpeed('pencil', 'instant');
const fastStart = Date.now();
await host.animateMove('pencil', 'left', 14);
assert.equal(sprite.x, 22);
assert(Date.now() - fastStart < 200, 'instant mode does not animate');
assert.throws(() => host.setSpeed('pencil', 0), /Speed/);
assert.throws(() => host.setSpeed('pencil', Infinity), /Speed/);
assert.throws(() => host.setSpeed('pencil', 100001), /Speed/);

host.setSpeed('pencil', 40);
const cancelled = host.animateMove('pencil', 'right', 200);
await sleep(70);
const stopStart = Date.now();
host.stopAnimations();
await cancelled;
const position = sprite.x;
assert(Date.now() - stopStart < 150, 'stop resolves immediately');
await sleep(50);
assert.equal(sprite.x, position, 'no frames run after stop');
assert(position < 222, 'cancelled movement did not finish');

host.setSpeed('pencil', 20);
const changing = host.animateMove('pencil', 'up', 100);
await sleep(40);
host.setSpeed('pencil', null);
await changing;
assert.equal(sprite.y, -93, 'changing to instant completes an in-flight move');
const old = host.create('other');
host.setSpeed('other', 10);
const removed = host.animateMove('other', 'down', 100);
host.remove('other');
await removed;
assert.equal(host.get('other'), null);
assert.equal(old.y, 0);
const source = 'add library "Draw"\ndefine \'pencil\' as drawing sprite\nset the speed of \'pencil\' to 200\n\'pencil\' move right "10"\nset the speed of \'pencil\' to instant';
assert.equal(diagnostics.validate(source, 'draw.enppl'), true);
console.log('E++ 1.3.5 animated Draw timing, controls, speed and cancellation checks passed.');
