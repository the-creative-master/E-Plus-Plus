const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { chromium } = require('playwright-core');
const { GalleryStore, createServer } = require('../server.js');
(async () => {
  const exe = [process.env.EPP_BROWSER, process.env.CHROME_BIN, '/usr/bin/chromium'].find(p => p && fs.existsSync(p));
  if (!exe) throw new Error('Set EPP_BROWSER to a Chromium executable.');
  const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'epp-hub-'));
  let server, browser;
  try {
    server = createServer(await new GalleryStore(path.join(temp, 'gallery.json')).init());
    await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
    browser = await chromium.launch({ executablePath: exe, args: ['--no-sandbox'] });
    const page = await browser.newPage({ viewport: { width: 1200, height: 800 } });
    const errors = []; page.on('pageerror', e => errors.push(String(e)));
    await page.goto(`http://127.0.0.1:${server.address().port}`);
    assert.equal(await page.locator('#commandPalette').count(), 0);
    assert((await page.locator('.activity-bar button').count()) > 20);
    await page.locator('#editor').focus(); await page.keyboard.press('Control+Shift+P');
    assert.equal(await page.locator('#studioActions').isVisible(), true);
    assert.equal(await page.evaluate(() => document.activeElement.id), 'toolsSearch');
    assert.equal(await page.locator('.tools-feature').count(), 24);
    assert.equal(await page.locator('.tools-project').count(), await page.evaluate(() => Object.keys(files).length));
    await page.locator('#toolsSearch').fill('hello');
    assert((await page.locator('.tools-project').count()) >= 1);
    await page.locator('.tools-project').first().click();
    assert.equal(await page.locator('#studioActions').isVisible(), false);
    await page.keyboard.press('Control+Shift+P'); await page.locator('#btnEditFeatures').click();
    await page.getByLabel('EShare in sidebar').uncheck();
    await page.getByLabel('EShare in Tools').uncheck();
    await page.locator('#featureDone').click();
    assert.equal(await page.locator('#extraSidebar [data-hub-id="eshare"]').count(), 0);
    await page.locator('#btnTools').click();
    assert.equal(await page.locator('#toolsFeatureList [data-hub-id="eshare"]').count(), 0);
    await page.reload();
    await page.locator('#btnTools').click();
    assert.equal(await page.locator('#toolsFeatureList [data-hub-id="eshare"]').count(), 0);
    await page.locator('#btnEditFeatures').click();
    await page.getByLabel('EShare in Tools').check();
    await page.getByLabel('EShare in sidebar').check();
    await page.locator('#featureDone').click();
    await page.locator('#btnTools').click();
    await page.locator('#toolsFeatureList [data-hub-id="eshare"]').click();
    assert.equal(await page.locator('#eshareDialog').isVisible(), true);
    await page.locator('#eshareClose').click();
    await page.locator('#btnSidebarEdit').click();
    await page.locator('[data-feature-preset="essential"]').click();
    assert.equal(await page.getByLabel('News in sidebar').isChecked(), false);
    await page.locator('[data-feature-preset="default"]').click();
    assert.equal(await page.getByLabel('News in sidebar').isChecked(), true);
    await page.locator('#featureDone').click();
    await page.keyboard.press('Control+Shift+P');
    await page.locator('#toolsSearch').fill('news');
    await page.locator('#toolsFeatureList [data-hub-id="news"]').click();
    await page.waitForURL('**/news.html');
    assert((await page.locator('body').innerText()).indexOf('RELEASE 1.4') < (await page.locator('body').innerText()).indexOf('RELEASE 1.4a2'));
    assert.equal(await page.locator('img').evaluateAll(imgs => imgs.every(i => i.complete && i.naturalWidth > 0)), true);
    assert.deepEqual(errors, []);
    console.log('Studio Tools hub, shortcut toggles, persistence, projects and news archive checks passed.');
  } finally { if (browser) await browser.close(); if (server) await new Promise(resolve => server.close(resolve)); fs.rmSync(temp, { recursive: true, force: true }); }
})().catch(e => { console.error(e); process.exitCode = 1; });
