#!/usr/bin/env node
// Rebuild the offline browser lexer from the native C++ source with Zig.
// Usage: ZIG=/path/to/zig node tools/build-lexer-wasm.mjs
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sources = ['include/lexer.hpp', 'src/lexer.cpp', 'src/wasm_lexer.cpp'];
const hash = createHash('sha256');
for (const file of sources) hash.update(file + '\0').update(readFileSync(path.join(root, file)));
const sourceHash = hash.digest('hex');
const temp = mkdtempSync(path.join(os.tmpdir(), 'epp-lexer-'));
try {
  const output = path.join(temp, 'lexer.wasm');
  execFileSync(process.env.ZIG || 'zig', [
    'c++', '-target', 'wasm32-wasi', '-std=c++17', '-Oz', '-s', '-fno-exceptions',
    '-mexec-model=reactor', '-DEPP_BROWSER_PLAINTEXT', '-Iinclude',
    'src/lexer.cpp', 'src/wasm_lexer.cpp',
    '-Wl,--export=epp_lexer_alloc', '-Wl,--export=epp_lexer_free',
    '-Wl,--export=epp_lexer_tokenize', '-o', output
  ], { cwd: root, stdio: 'inherit' });
  const binary = readFileSync(output);
  const base64 = binary.toString('base64').match(/.{1,100}/g);
  const generated = `/* Generated by tools/build-lexer-wasm.mjs from src/lexer.cpp; do not edit.\n` +
    ` * The bytes are compiled WebAssembly, not program outputs. */\n` +
    `(function (root) {\n  var build = { sourceSha256: '${sourceHash}', base64: [\n` +
    base64.map(line => `    '${line}'`).join(',\n') +
    `\n  ].join('') };\n  if (typeof module !== 'undefined' && module.exports) module.exports = build;\n` +
    `  else root.EPP_NATIVE_LEXER_BUILD = build;\n})(typeof globalThis !== 'undefined' ? globalThis : this);\n`;
  writeFileSync(path.join(root, 'js/native-lexer-wasm.js'), generated);
  console.log(`Built ${binary.length} bytes of WebAssembly from ${sources.join(', ')}.`);
  console.log('C++ source SHA-256:', sourceHash);
} finally {
  rmSync(temp, { recursive: true, force: true });
}
